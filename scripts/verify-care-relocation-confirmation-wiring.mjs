import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';

const care = readFileSync('src/pages/CareEncyclopedia.tsx', 'utf8');

for (const required of [
  'RelocationConfirmationDialog',
  'createCareRelocationConfirmationController',
  'applyCareCanonicalAquariums',
  'sourceAquarium={targetAquarium || undefined}',
  'onOpenRelocationConfirmation={openRelocationConfirmation}',
  'request={relocationController.attempt.request}',
  'facts={relocationController.attempt.facts}',
  'getRepository: getCurrentAquaGuideRepository',
  "if (result.status === 'executed')",
  'applyCanonicalCareState(result.postAquariums)',
  'const freshAquariums = await relocationController.reconcile()',
  'applyCanonicalCareState(freshAquariums)',
  'const aquariums = canonicalAquariums ?? appState.aquariums',
  'showCanonicalAquariums: setCanonicalAquariums',
  'persistMirror: patch => patchLocalAppState(patch)',
  'setCanonicalAquariums(null)',
]) {
  assert.match(care, new RegExp(required.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')));
}

// Page wiring may obtain the repository provider for the controller, but must
// never call the relocation mutation directly. #63 remains the only write gate.
assert.doesNotMatch(care, /\.relocateLivestock\s*\(/);
assert.doesNotMatch(care, /repository\.relocateLivestock/);

// Operation identity must be generated by controller creation in the explicit
// opener event, not by Care render/useMemo/effect code.
const openerIndex = care.indexOf('const openRelocationConfirmation =');
const controllerCreateIndex = care.indexOf('createCareRelocationConfirmationController({', openerIndex);
assert.ok(openerIndex >= 0 && controllerCreateIndex > openerIndex);
assert.doesNotMatch(care, /useMemo\([^)]*createCareRelocationConfirmationController/s);
assert.doesNotMatch(care, /useEffect\([^)]*createCareRelocationConfirmationController/s);

// Canonical success must be applied before the dialog receives the terminal
// result back, and mirror persistence is isolated inside the non-throwing helper.
const executeWrapper = care.match(/executeFreshRelocation=\{async request => \{([\s\S]*?)\n          \}\}/)?.[1] || '';
assert.match(executeWrapper, /const result = await relocationController\.execute\(\)/);
assert.match(executeWrapper, /applyCanonicalCareState\(result\.postAquariums\)/);
assert.match(executeWrapper, /return result/);
assert.ok(
  executeWrapper.indexOf('applyCanonicalCareState(result.postAquariums)') < executeWrapper.indexOf('return result'),
  'visible canonical Care state must refresh before returning executed result to the dialog',
);

// Reconciliation is canonical read + view/mirror refresh only. No mutation call
// exists in this handler, so uncertain attempts cannot become blind retries.
const reconcileWrapper = care.match(/onReconcile=\{async \(\) => \{([\s\S]*?)\n          \}\}/)?.[1] || '';
assert.match(reconcileWrapper, /await relocationController\.reconcile\(\)/);
assert.match(reconcileWrapper, /applyCanonicalCareState\(freshAquariums\)/);
assert.doesNotMatch(reconcileWrapper, /execute\(|relocateLivestock|createCareRelocationConfirmationController/);

console.log('Care relocation confirmation wiring contract passed: opener creates one controller, page cannot bypass fresh policy, canonical success/reconcile refresh visible state, and mirror sync is secondary');
