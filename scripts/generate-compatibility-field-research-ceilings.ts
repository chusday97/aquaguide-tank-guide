import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname } from 'node:path';

const arg = (name: string) => {
  const prefix = `--${name}=`;
  return process.argv.find(value => value.startsWith(prefix))?.slice(prefix.length);
};

const input = arg('input') || 'evaluation/product/compatibility-research-review-queue.v1.json';
const output = arg('output') || 'src/data/compatibilityFieldResearchCeilings.ts';

type QueueItem = {
  queue?: string;
  researchKey?: string;
  scientificName?: string;
  unresolvedFields?: string[];
  reasonCodes?: string[];
  identity?: { status?: string; canonicalName?: string | null };
  researchHistory?: {
    rounds?: number;
    attemptedUrls?: string[];
    attemptedRouteIds?: string[];
  };
  catalogObjects?: Array<{ speciesId?: string; scientificName?: string; isVariant?: boolean }>;
};

const manifest = JSON.parse(readFileSync(input, 'utf8')) as { items?: QueueItem[] };
const rows = (manifest.items || [])
  .filter(item => item.queue === 'evidence_ceiling_review')
  .flatMap(item => {
    const history = item.researchHistory;
    const reasonCodes = item.reasonCodes || [];
    if (item.identity?.status !== 'verified') return [];
    if ((history?.rounds || 0) < 2) return [];
    if (!reasonCodes.includes('generic_source_strategy_exhausted')) return [];
    if (!reasonCodes.includes('specialized_source_routes_exhausted')) return [];
    return (item.catalogObjects || [])
      .filter(object => object.speciesId && !object.isVariant)
      .map(object => ({
        speciesId: object.speciesId!,
        scientificName: object.scientificName || item.scientificName || item.researchKey || '',
        fields: [...new Set(item.unresolvedFields || [])].sort(),
        reasonCode: 'compatibility_field_source_strategy_exhausted' as const,
        sourceArtifact: input,
        researchRounds: history?.rounds || 0,
        attemptedUrlCount: new Set(history?.attemptedUrls || []).size,
        attemptedRouteIds: [...new Set(history?.attemptedRouteIds || [])].sort(),
      }))
      .filter(row => row.fields.length > 0);
  })
  .sort((a, b) => a.speciesId.localeCompare(b.speciesId));

const source = `// AUTO-GENERATED by scripts/generate-compatibility-field-research-ceilings.ts.
// Research-planning state only. These rows stop repeated source discovery after reviewed
// source strategies are exhausted; they do NOT create Compatibility runtime authority
// and do NOT assert any husbandry or compatibility fact.

export type CompatibilityFieldResearchCeiling = {
  speciesId: string;
  scientificName: string;
  fields: string[];
  reasonCode: 'compatibility_field_source_strategy_exhausted';
  sourceArtifact: string;
  researchRounds: number;
  attemptedUrlCount: number;
  attemptedRouteIds: string[];
};

export const compatibilityFieldResearchCeilings: CompatibilityFieldResearchCeiling[] = ${JSON.stringify(rows, null, 2)};

export const getCompatibilityFieldResearchCeiling = (speciesId: string, field: string) =>
  compatibilityFieldResearchCeilings.find(row => row.speciesId === speciesId && row.fields.includes(field)) ?? null;
`;

mkdirSync(dirname(output), { recursive: true });
writeFileSync(output, source);
console.log(JSON.stringify({
  input,
  output,
  speciesCount: rows.length,
  fieldCount: rows.reduce((sum, row) => sum + row.fields.length, 0),
  promotionAllowed: false,
  writesAuthority: false,
}, null, 2));
