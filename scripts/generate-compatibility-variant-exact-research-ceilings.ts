import { readFileSync, writeFileSync } from 'node:fs';
import { dirname } from 'node:path';
import { mkdirSync } from 'node:fs';

const arg = (name: string) => {
  const prefix = `--${name}=`;
  return process.argv.find(item => item.startsWith(prefix))?.slice(prefix.length);
};

const input = arg('input') || 'evaluation/product/compatibility-variant-exact-evidence-triage.v1.json';
const output = arg('output') || 'src/data/compatibilityVariantExactResearchCeilings.ts';

type ExactEvidenceTriage = {
  objects?: Array<{
    speciesId?: string;
    canonicalScientificName?: string;
    status?: string;
    unresolvedFields?: string[];
    researchRuns?: Array<{ discoveryStatus?: string }>;
  }>;
};

const triage = JSON.parse(readFileSync(input, 'utf8')) as ExactEvidenceTriage;
const rows = (triage.objects || [])
  .filter(object => object.status === 'discovery_evidence_ceiling')
  .map(object => {
    const speciesId = String(object.speciesId || '');
    const fields = [...new Set((object.unresolvedFields || []).filter(Boolean))].sort();
    const researchRounds = (object.researchRuns || []).filter(run => run.discoveryStatus === 'discovery_empty').length;
    if (!speciesId || fields.length === 0) return null;
    if (researchRounds < 2) {
      throw new Error(`exact_research_ceiling_requires_two_empty_rounds:${speciesId}:${researchRounds}`);
    }
    return {
      speciesId,
      status: 'exact_object_evidence_ceiling' as const,
      baseScientificName: String(object.canonicalScientificName || ''),
      fields,
      reasonCode: 'variant_exact_object_research_exhausted' as const,
      sourceArtifact: input,
      researchRounds,
    };
  })
  .filter((row): row is NonNullable<typeof row> => Boolean(row))
  .sort((a, b) => a.speciesId.localeCompare(b.speciesId));

const body = `// AUTO-GENERATED by scripts/generate-compatibility-variant-exact-research-ceilings.ts
// Research-planning only: these records stop repeated exact-object source discovery after
// two independent empty rounds. They do not create runtime Compatibility authority.

export type CompatibilityVariantExactResearchCeiling = {
  speciesId: string;
  status: 'exact_object_evidence_ceiling';
  baseScientificName: string;
  fields: string[];
  reasonCode: 'variant_exact_object_research_exhausted';
  sourceArtifact: string;
  researchRounds: number;
};

export const compatibilityVariantExactResearchCeilings: CompatibilityVariantExactResearchCeiling[] = ${JSON.stringify(rows, null, 2)};

export const getCompatibilityVariantExactResearchCeiling = (speciesId: string, field?: string) =>
  compatibilityVariantExactResearchCeilings.find(item => (
    item.speciesId === speciesId
    && (!field || item.fields.includes(field))
  ));
`;

mkdirSync(dirname(output), { recursive: true });
writeFileSync(output, body);
console.log(JSON.stringify({
  input,
  output,
  objectCount: rows.length,
  fieldCount: rows.reduce((sum, row) => sum + row.fields.length, 0),
  allTwoRoundCeilings: rows.every(row => row.researchRounds >= 2),
}, null, 2));
