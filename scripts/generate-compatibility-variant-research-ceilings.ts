import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname } from 'node:path';

const arg = (name: string) => {
  const prefix = `--${name}=`;
  return process.argv.find(value => value.startsWith(prefix))?.slice(prefix.length);
};

const input = arg('input') || 'evaluation/product/compatibility-variant-bridge-review.v1.json';
const appendInputs = (arg('append-input') || '')
  .split(',')
  .map(value => value.trim())
  .filter(Boolean);
const inputPaths = [...new Set([input, ...appendInputs])];
const output = arg('output') || 'src/data/compatibilityVariantResearchCeilings.ts';

type VariantBridgeManifest = {
  groups?: Array<{
    objects?: Array<{
      speciesId?: string;
      baseScientificName?: string;
      status?: string;
      unresolvedFields?: string[];
      candidateFields?: string[];
      reasonCodes?: string[];
    }>;
  }>;
};

type VariantCeilingRow = {
  speciesId: string;
  status: 'identity_evidence_ceiling' | 'field_bridge_evidence_ceiling';
  baseScientificName: string;
  fields: string[];
  reasonCode: 'variant_identity_research_exhausted' | 'variant_field_bridge_research_exhausted';
  sourceArtifact: string;
};

const rowBySpeciesId = new Map<string, VariantCeilingRow>();
for (const sourceArtifact of inputPaths) {
  const manifest = JSON.parse(readFileSync(sourceArtifact, 'utf8')) as VariantBridgeManifest;
  for (const object of (manifest.groups || []).flatMap(group => group.objects || [])) {
    if (object.status !== 'identity_evidence_ceiling' && object.status !== 'field_bridge_evidence_ceiling') continue;
    const speciesId = String(object.speciesId || '');
    const fields = [...new Set((object.status === 'identity_evidence_ceiling'
      ? (object.unresolvedFields || [])
      : (object.candidateFields || [])).filter(Boolean))].sort();
    if (!speciesId || fields.length === 0) continue;
    rowBySpeciesId.set(speciesId, {
      speciesId,
      status: object.status,
      baseScientificName: String(object.baseScientificName || ''),
      fields,
      reasonCode: (object.reasonCodes || []).includes('variant_identity_research_exhausted')
        ? 'variant_identity_research_exhausted'
        : 'variant_field_bridge_research_exhausted',
      sourceArtifact,
    });
  }
}

const rows = [...rowBySpeciesId.values()].sort((a, b) => a.speciesId.localeCompare(b.speciesId));

const body = `// AUTO-GENERATED by scripts/generate-compatibility-variant-research-ceilings.ts
// Research-planning only: these records stop repeated source research. They do not create Compatibility runtime authority.

export type CompatibilityVariantResearchCeiling = {
  speciesId: string;
  status: 'identity_evidence_ceiling' | 'field_bridge_evidence_ceiling';
  baseScientificName: string;
  fields: string[];
  reasonCode: 'variant_identity_research_exhausted' | 'variant_field_bridge_research_exhausted';
  sourceArtifact: string;
};

export const compatibilityVariantResearchCeilings: CompatibilityVariantResearchCeiling[] = ${JSON.stringify(rows, null, 2)};

export const getCompatibilityVariantResearchCeiling = (
  speciesId: string,
  field: string,
): CompatibilityVariantResearchCeiling | undefined => (
  compatibilityVariantResearchCeilings.find(item => item.speciesId === speciesId && item.fields.includes(field))
);
`;

mkdirSync(dirname(output), { recursive: true });
writeFileSync(output, body);
console.log(JSON.stringify({ input, appendInputs, inputPaths, output, count: rows.length, fieldCount: rows.reduce((sum, row) => sum + row.fields.length, 0) }, null, 2));
